"""SVGZ images against plain rectangles; gzip fixtures use Python's compressor."""
import base64
import gzip
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[2]
DRAWING = b'<svg xmlns="http://www.w3.org/2000/svg" width="8" height="4"><rect width="4" height="4" fill="red"/><rect x="4" width="4" height="4" fill="lime"/></svg>'
PLAIN = '<rect width="4" height="4" fill="red"/><rect x="4" width="4" height="4" fill="lime"/>'


def pack(data):
    return gzip.compress(data, mtime=0)


def uri(data):
    return 'data:image/svg+xml;base64,' + base64.b64encode(data).decode()


def image(data, sized=True):
    size = ' width="8" height="4"' if sized else ''
    return f'<image{size} href="{uri(data)}"/>'


def pair(name, cases):
    height = ((len(cases) + 3) // 4) * 8
    start = [f'<svg xmlns="http://www.w3.org/2000/svg" width="48" height="{height}">',
             '<!-- Generated by tst/gen/svgz.py. Expected drawings use only literal rectangles. -->',
             f'<rect width="48" height="{height}" fill="white"/>']
    actual, expected = start[:], start[:]
    for i, (label, content, plain) in enumerate(cases):
        x, y = 2 + i % 4 * 12, 2 + i // 4 * 8
        opening = f'<g id="{label}" data-box="{x} {y} 8 4" transform="translate({x} {y})">'
        actual.append(opening + content + '</g>')
        expected.append(opening + plain + '</g>')
    for directory, lines in [('unit', actual), ('expect', expected)]:
        (ROOT / 'tst' / directory / (name + '.svg')).write_text('\n'.join(lines + ['</svg>', '']))


packed = pack(DRAWING)
members = pack(DRAWING[:37]) + pack(DRAWING[37:])
header = b'\x1f\x8b\x08\x1e' + b'\0' * 4 + b'\0\x03'
header += struct.pack('<H', 6) + b'XY\x02\0ab' + b'caf\xe9.svg\0comment\0'
header += struct.pack('<H', zlib.crc32(header) & 0xffff)
optional = header + packed[10:]
nested = ('<svg xmlns="http://www.w3.org/2000/svg" width="8" height="4">' + image(packed) + '</svg>').encode()
feimage = f'<filter id="f" x="0" y="0" width="1" height="1"><feImage href="{uri(packed)}"/></filter><rect width="8" height="4" filter="url(#f)"/>'
pair('svgz-images', [
    ('gzip', image(packed), PLAIN),
    ('members', image(members), PLAIN),
    ('optional-header', image(optional), PLAIN),
    ('chunks', image(pack(b'<!--' + b'comment ' * 20000 + b'-->' + DRAWING)), PLAIN),
    ('nested', image(pack(nested)), PLAIN),
    ('filter-image', feimage, PLAIN),
    ('intrinsic-size', image(packed, sized=False), PLAIN),
    ('plain-xml', image(DRAWING), PLAIN),
])

crc = bytearray(packed)
crc[-8] ^= 1
size = bytearray(packed)
size[-4] ^= 1
flags = bytearray(packed)
flags[3] |= 0x20
broken = [('signature', packed[:2]), ('header', packed[:8]), ('payload', packed[:30]),
          ('trailer', packed[:-1]), ('crc', bytes(crc)), ('size', bytes(size)),
          ('flags', bytes(flags)), ('trailing', packed + b'junk'),
          ('last-member', packed + packed[:-4]), ('empty', pack(b'')),
          ('not-svg', pack(b'<html/>')), ('invalid-xml', pack(b'<svg>')),
          ('double-gzip', pack(packed))]
background = '<rect width="8" height="4" fill="#123456"/>'
pair('svgz-errors', [(name, background + image(data), background) for name, data in broken])
pair('svgz.nodecompress', [
    ('no-decompressor', background + image(packed), background),
    ('plain-without-decompressor', image(DRAWING), PLAIN),
])

# Actual compressed root files exercise svg_library_parse as well as images.
for name, data, drawing in [
    ('svgz-root', packed, DRAWING.decode()),
    ('svgz-root.nodecompress', packed, '<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>'),
    ('svgz-root-crc', bytes(crc), '<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>'),
]:
    (ROOT / 'tst/unit' / (name + '.svgz')).write_bytes(data)
    (ROOT / 'tst/expect' / (name + '.svg')).write_text(drawing + '\n')
